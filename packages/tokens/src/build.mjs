// figma/export.json  ->  build/
//
//   tokens.css        --ax-* primitives and mode-independent values
//   light.css         --ax-* semantic values for light
//   dark.css          --ax-* semantic values for dark
//   webawesome.css    --wa-* -> var(--ax-*) for every *owned* WA property
//   tokens.json       normalized tokens (consumed by the audit and Storybook)
//   tokens.dtcg.json  W3C Design Tokens format, for other tools
//   tokens.js/.d.ts   typed JS access: tokens['color/brand/50'].cssVar
//   _tokens.scss      $ax-* variables that point at the CSS custom properties
//   breakpoints.css   @custom-media --ax-bp-* (for PostCSS / Lightning CSS)
//   _breakpoints.scss $ax-breakpoints map + ax-up() mixin (raw values: @media
//                     can't use var())
//   figma/code-syntax.json  round-trip: the CSS name each Figma variable
//                     should show in Dev Mode, and which WA props it feeds
//
// Nothing here is hand-edited. packages/theme copies the CSS into its src/
// (committed) so token changes show up as reviewable diffs in PRs.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { normalize } from './normalize.mjs';
import { owned } from './alias-map.mjs';

const PKG = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(PKG, 'build');

// Cascade layers: all of WA's, in WA's order, then ours. Declaring the full
// list means our layers win regardless of stylesheet load order. The audit
// fails if upstream's list stops being a prefix of this one.
export const AX_LAYERS = ['ax-tokens', 'ax-theme', 'ax-parts'];

// Mirrors the selectors WA's default theme uses for each scheme. WA writes its
// semantic colors directly onto these elements, so we must match the same
// elements (inheritance from :root alone would lose to WA on .wa-dark etc).
export const SELECTORS = {
  base: [':where(:root)', '.wa-light', '.wa-dark', '.wa-invert', '.ax-theme'],
  light: [':where(:root)', '.wa-light', '.wa-dark .wa-invert'],
  dark: ['.wa-dark', '.wa-invert', '.wa-light .wa-invert'],
};

const HEADER = (src) =>
  `/* GENERATED by @soar-awesome/tokens from ${src}. Do not edit: changes are overwritten and fail CI. */\n`;

export function build({ exportJson, upstreamLayers }) {
  const tokens = normalize(exportJson);
  const byName = new Map(tokens.map((t) => [t.name, t]));

  const layerStatement = `@layer ${[...upstreamLayers, ...AX_LAYERS].join(', ')};\n`;
  const block = (layer, selectors, decls) =>
    decls.length ? `@layer ${layer} {\n  ${selectors.join(',\n  ')} {\n${decls.map((d) => `    ${d}`).join('\n')}\n  }\n}\n` : '';

  const decl = (t, mode) => `${t.cssVar}: ${t.values[mode]};`;
  const baseTokens = tokens.filter((t) => 'base' in t.values);
  const modalTokens = tokens.filter((t) => !('base' in t.values));

  const files = {};
  files['tokens.css'] =
    HEADER('figma/export.json') + layerStatement + '\n' + block('ax-tokens', [':where(:root)', '.ax-theme'], baseTokens.map((t) => decl(t, 'base')));
  files['light.css'] = HEADER('figma/export.json') + block('ax-tokens', SELECTORS.light, modalTokens.filter((t) => t.values.light).map((t) => decl(t, 'light')));
  files['dark.css'] = HEADER('figma/export.json') + block('ax-tokens', SELECTORS.dark, modalTokens.filter((t) => t.values.dark).map((t) => decl(t, 'dark')));

  const waDecls = [];
  const missing = [];
  for (const [waProp, figmaName] of Object.entries(owned).sort(([a], [b]) => a.localeCompare(b))) {
    const t = byName.get(figmaName);
    if (!t) {
      missing.push(`${waProp} -> ${figmaName}`);
      continue;
    }
    waDecls.push(`${waProp}: var(${t.cssVar});`);
  }
  if (missing.length) {
    throw new Error(
      `alias-map.mjs points at Figma variables that don't exist (renamed or deleted in Figma?):\n  ${missing.join('\n  ')}`,
    );
  }
  files['webawesome.css'] = HEADER('src/alias-map.mjs') + block('ax-theme', SELECTORS.base, waDecls);

  files['tokens.json'] = JSON.stringify(tokens, null, 2) + '\n';
  files['tokens.dtcg.json'] = JSON.stringify(toDtcg(tokens), null, 2) + '\n';
  files['tokens.js'] =
    `// GENERATED\nexport const tokens = ${JSON.stringify(Object.fromEntries(tokens.map((t) => [t.name, { cssVar: t.cssVar, type: t.type, values: t.values }])), null, 2)};\n`;
  files['tokens.d.ts'] =
    `// GENERATED\nexport type TokenName =\n${tokens.map((t) => `  | '${t.name}'`).join('\n')};\n` +
    `export interface Token { cssVar: \`--ax-\${string}\`; type: string; values: Partial<Record<'base' | 'light' | 'dark', string>> }\n` +
    `export declare const tokens: Record<TokenName, Token>;\n`;
  files['_tokens.scss'] =
    `// GENERATED. These resolve to CSS custom properties so light/dark still work.\n` +
    tokens.map((t) => `$${t.cssVar.slice(2)}: var(${t.cssVar});`).join('\n') +
    '\n';

  // Breakpoints: emitted as raw values, because @media can't read var().
  const bps = tokens
    .filter((t) => t.name.startsWith('breakpoint/'))
    .map((t) => ({ key: t.name.split('/').pop(), value: t.values.base }))
    .sort((a, b) => parseFloat(a.value) - parseFloat(b.value));
  files['breakpoints.css'] =
    HEADER('figma/export.json') +
    `/* Mobile-first min-width queries. Needs postcss-custom-media or Lightning CSS until browsers ship @custom-media. */\n` +
    bps.map((b) => `@custom-media --ax-bp-${b.key} (width >= ${b.value});`).join('\n') +
    '\n';
  files['_breakpoints.scss'] =
    `// GENERATED. Raw values on purpose: @media can't use CSS custom properties.\n` +
    `$ax-breakpoints: (\n${bps.map((b) => `  ${b.key}: ${b.value},`).join('\n')}\n);\n\n` +
    `/// Mobile-first: styles apply at the named breakpoint and wider.\n` +
    `@mixin ax-up($name) {\n  @media (width >= map-get($ax-breakpoints, $name)) {\n    @content;\n  }\n}\n`;
  const breakpointsJs =
    `export const breakpoints = ${JSON.stringify(Object.fromEntries(bps.map((b) => [b.key, b.value])), null, 2)};\n` +
    `/** Ready for matchMedia(): media.md === '(width >= 48rem)' */\n` +
    `export const media = ${JSON.stringify(Object.fromEntries(bps.map((b) => [b.key, `(width >= ${b.value})`])), null, 2)};\n`;
  files['tokens.js'] += breakpointsJs;
  files['tokens.d.ts'] +=
    `export type Breakpoint = ${bps.map((b) => `'${b.key}'`).join(' | ') || 'never'};\n` +
    `export declare const breakpoints: Record<Breakpoint, string>;\n` +
    `export declare const media: Record<Breakpoint, string>;\n`;

  const feeds = {};
  for (const [waProp, figmaName] of Object.entries(owned)) (feeds[figmaName] ??= []).push(waProp);
  files['figma/code-syntax.json'] =
    JSON.stringify(
      tokens.map((t) => ({ id: t.id, name: t.name, codeSyntax: { WEB: `var(${t.cssVar})` }, feeds: feeds[t.name] ?? [] })),
      null,
      2,
    ) + '\n';

  return { tokens, files };
}

function toDtcg(tokens) {
  const root = {};
  for (const t of tokens) {
    let node = root;
    for (const seg of t.name.split('/')) node = node[seg] ??= {};
    const modes = Object.keys(t.values);
    node.$type = t.type;
    node.$value = dtcgValue(t.values[modes.includes('base') ? 'base' : 'light']);
    if (!modes.includes('base')) node.$extensions = { 'com.soar.modes': Object.fromEntries(modes.map((m) => [m, dtcgValue(t.values[m])])) };
    if (t.description) node.$description = t.description;
  }
  return root;
}

function dtcgValue(v) {
  const m = /^var\(--ax-(.+)\)$/.exec(v);
  return m ? `{${m[1].replace(/-/g, '.')}}` : v;
}

export function writeBuild(files, outDir = OUT) {
  for (const [rel, content] of Object.entries(files)) {
    mkdirSync(dirname(join(outDir, rel)), { recursive: true });
    writeFileSync(join(outDir, rel), content);
  }
}

// Run as a script (not imported). Compare URLs, not strings: works on Windows too.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const exportJson = JSON.parse(readFileSync(join(PKG, 'figma/export.json'), 'utf8'));
  const upstream = JSON.parse(readFileSync(join(PKG, 'upstream/webawesome.tokens.json'), 'utf8'));
  const { tokens, files } = build({ exportJson, upstreamLayers: upstream.layers });
  writeBuild(files);
  console.log(`tokens: ${tokens.length} Figma variables -> ${Object.keys(owned).length} owned WA properties`);
}
