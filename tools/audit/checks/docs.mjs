// Documentation completeness. Warnings, not errors: missing docs shouldn't
// block a release, but they show on the scorecard until fixed.
import { exists, json, read } from '../context.mjs';

const CEM = 'packages/components/custom-elements.json';

export default {
  id: 'docs',
  title: 'Docs',
  description: 'Has a story with a generated Docs page; Soar components describe every attribute, slot, part, event and CSS property.',
  appliesTo: ['atom', 'molecule', 'organism'],
  run(component) {
    const f = [];
    if (!component.storyFile) {
      return [{ level: 'warn', rule: 'story', message: `No story documents <${component.tag}>. Add one under apps/storybook/stories/${component.layer}s/.` }];
    }
    const story = read(component.storyFile);
    if (!/tags:\s*\[[^\]]*'autodocs'/.test(story)) {
      f.push({ level: 'warn', rule: 'autodocs', file: component.storyFile, message: "Story isn't tagged 'autodocs', so it has no Docs page." });
    }

    if (component.owner === 'web-awesome') {
      if (!/soar:\s*\n?\s*['"`][^'"`]+/.test(story)) {
        f.push({ level: 'warn', rule: 'soar-note', file: component.storyFile, message: 'atomMeta has no `soar:` note saying what Soar changes (or "No component-specific changes").' });
      }
      return f;
    }

    // Soar components: the custom-elements manifest is generated by the components build.
    if (!exists(CEM)) {
      return [...f, { level: 'skipped', rule: 'manifest', message: 'custom-elements.json not built yet (run npm run build) — API descriptions not checked.' }];
    }
    const decl = json(CEM)
      .modules.flatMap((m) => m.declarations ?? [])
      .find((d) => d.tagName === component.tag);
    if (!decl) return [...f, { level: 'warn', rule: 'manifest', message: `<${component.tag}> is missing from custom-elements.json (missing @tag JSDoc?)` }];
    if (!decl.description && !decl.summary) f.push({ level: 'warn', rule: 'description', file: component.sourceFile, message: 'The class has no JSDoc description.' });

    const groups = {
      attribute: (decl.attributes ?? []).filter((a) => !['dir', 'lang'].includes(a.name)),
      slot: decl.slots ?? [],
      part: decl.cssParts ?? [],
      event: decl.events ?? [],
      'CSS property': decl.cssProperties ?? [],
    };
    for (const [kind, items] of Object.entries(groups)) {
      for (const item of items) {
        if (!item.description?.trim()) {
          f.push({ level: 'warn', rule: 'api-description', file: component.sourceFile, message: `${kind} "${item.name || '(default)'}" has no description.` });
        }
      }
    }
    return f;
  },
};
